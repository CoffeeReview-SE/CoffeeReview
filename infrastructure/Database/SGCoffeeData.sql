-- SaigonCoffee database schema + initial reference data
-- DBMS: PostgreSQL (matches SGCoffee/.env.example: Host/Port 5432)
-- Run from the SGCoffee repository root with a PostgreSQL user allowed to create tables.
-- This script does not DROP existing tables and can be run repeatedly for seed rows.

BEGIN;

CREATE TABLE IF NOT EXISTS language (
    language_code VARCHAR(10) PRIMARY KEY,
    language_name_vi VARCHAR(80) NOT NULL,
    native_name VARCHAR(80) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS brand (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name VARCHAR(160) NOT NULL UNIQUE,
    type VARCHAR(80),
    description TEXT,
    description_language_code VARCHAR(10) REFERENCES language(language_code) ON DELETE RESTRICT,
    description_source_url TEXT,
    logo_url TEXT,
    website_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS branch (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES brand(brand_id) ON DELETE RESTRICT,
    branch_name VARCHAR(180),
    address TEXT NOT NULL,
    latitude DOUBLE PRECISION CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    phone VARCHAR(30),
    opening_hours JSONB,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_branch_brand_id ON branch(brand_id);
CREATE INDEX IF NOT EXISTS ix_branch_active ON branch(is_active);

CREATE TABLE IF NOT EXISTS submission (
    submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(20) NOT NULL CHECK (target_type IN ('BRAND','BRANCH','MENU_ITEM')),
    target_id BIGINT,
    data_json JSONB NOT NULL,
    suggested_name VARCHAR(180),
    suggested_address TEXT,
    suggested_latitude DOUBLE PRECISION CHECK (suggested_latitude IS NULL OR suggested_latitude BETWEEN -90 AND 90),
    suggested_longitude DOUBLE PRECISION CHECK (suggested_longitude IS NULL OR suggested_longitude BETWEEN -180 AND 180),
    created_by BIGINT,
    processed_by BIGINT,
    created_brand_id BIGINT REFERENCES brand(brand_id) ON DELETE SET NULL,
    created_branch_id BIGINT REFERENCES branch(branch_id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_submission_status_created ON submission(status, created_at);

CREATE TABLE IF NOT EXISTS visit_session (
    session_id UUID PRIMARY KEY,
    visitor_id UUID,
    ended_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activity_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    device_type VARCHAR(30),
    referrer TEXT,
    is_admin_session BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_visit_session_visitor_id ON visit_session(visitor_id);
CREATE INDEX IF NOT EXISTS ix_visit_session_open_activity ON visit_session(last_activity_at DESC) WHERE ended_at IS NULL AND NOT is_admin_session;
CREATE INDEX IF NOT EXISTS ix_visit_session_started_at ON visit_session(started_at);

CREATE TABLE IF NOT EXISTS page_view (
    page_view_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID,
    session_id UUID REFERENCES visit_session(session_id) ON DELETE SET NULL,
    page_path TEXT NOT NULL,
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    brand_id BIGINT REFERENCES brand(brand_id) ON DELETE SET NULL,
    branch_id BIGINT REFERENCES branch(branch_id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_page_view_event_id ON page_view(event_id);
CREATE INDEX IF NOT EXISTS ix_page_view_session_id ON page_view(session_id);
CREATE INDEX IF NOT EXISTS ix_page_view_viewed_at ON page_view(viewed_at);
CREATE INDEX IF NOT EXISTS ix_page_view_brand ON page_view(brand_id, viewed_at);
CREATE INDEX IF NOT EXISTS ix_page_view_branch ON page_view(branch_id, viewed_at);

CREATE TABLE IF NOT EXISTS audio_play (
    audio_play_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID,
    brand_id BIGINT REFERENCES brand(brand_id) ON DELETE SET NULL,
    branch_id BIGINT REFERENCES branch(branch_id) ON DELETE SET NULL,
    session_id UUID REFERENCES visit_session(session_id) ON DELETE SET NULL,
    language_code VARCHAR(10) NOT NULL REFERENCES language(language_code) ON DELETE RESTRICT,
    played_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_audio_play_event_id ON audio_play(event_id);
CREATE INDEX IF NOT EXISTS ix_audio_play_brand_time ON audio_play(brand_id, played_at);
CREATE INDEX IF NOT EXISTS ix_audio_play_language_time ON audio_play(language_code, played_at);
CREATE INDEX IF NOT EXISTS ix_audio_play_session_id ON audio_play(session_id);
CREATE INDEX IF NOT EXISTS ix_audio_play_played_at ON audio_play(played_at);

