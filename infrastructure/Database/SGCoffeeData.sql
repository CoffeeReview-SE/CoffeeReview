-- SaigonCoffee database schema + initial reference data
-- DBMS: PostgreSQL (matches SGCoffee/.env.example: Host/Port 5432)
-- Run from the SGCoffee repository root with a PostgreSQL user allowed to create tables.
-- This script does not DROP existing tables and can be run repeatedly for seed rows.

BEGIN;

CREATE TABLE IF NOT EXISTS role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(30) NOT NULL UNIQUE,
    role_name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS user_account (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    display_name VARCHAR(150),
    email VARCHAR(254) UNIQUE,
    phone VARCHAR(30),
    avatar_url TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','LOCKED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS user_role (
    user_id BIGINT NOT NULL REFERENCES user_account(user_id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES role(role_id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS language (
    language_code VARCHAR(10) PRIMARY KEY,
    language_name_vi VARCHAR(80) NOT NULL,
    native_name VARCHAR(80) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS brand (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name VARCHAR(160) NOT NULL UNIQUE,
    description TEXT,
    description_language_code VARCHAR(10) REFERENCES language(language_code) ON DELETE RESTRICT,
    description_source_url TEXT,
    logo_url TEXT,
    website_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS branch (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT NOT NULL REFERENCES brand(brand_id) ON DELETE RESTRICT,
    branch_name VARCHAR(180),
    address TEXT NOT NULL,
    latitude DOUBLE PRECISION CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    phone VARCHAR(30),
    opening_hours JSONB,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_branch_brand_id ON branch(brand_id);
CREATE INDEX IF NOT EXISTS ix_branch_active ON branch(is_active);

CREATE TABLE IF NOT EXISTS menu_item (
    menu_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES branch(branch_id) ON DELETE RESTRICT,
    item_name VARCHAR(180) NOT NULL,
    price NUMERIC(12,2) CHECK (price IS NULL OR price >= 0),
    description TEXT,
    image_url TEXT,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_menu_item_branch_id ON menu_item(branch_id);

CREATE TABLE IF NOT EXISTS review (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES branch(branch_id) ON DELETE RESTRICT,
    user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    menu_item_id BIGINT REFERENCES menu_item(menu_item_id) ON DELETE SET NULL,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(1000),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','HIDDEN')),
    moderated_by BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    moderated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_review_branch_status ON review(branch_id, status);
CREATE INDEX IF NOT EXISTS ix_review_created_at ON review(created_at);

CREATE TABLE IF NOT EXISTS review_report (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES review(review_id) ON DELETE CASCADE,
    reporter_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RESOLVED','DISMISSED')),
    processed_by BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    processed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_review_report_status ON review_report(status);

CREATE TABLE IF NOT EXISTS submission (
    submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(20) NOT NULL CHECK (target_type IN ('BRAND','BRANCH','MENU_ITEM')),
    target_id BIGINT,
    data_json JSONB NOT NULL,
    suggested_name VARCHAR(180),
    suggested_address TEXT,
    suggested_latitude DOUBLE PRECISION CHECK (suggested_latitude IS NULL OR suggested_latitude BETWEEN -90 AND 90),
    suggested_longitude DOUBLE PRECISION CHECK (suggested_longitude IS NULL OR suggested_longitude BETWEEN -180 AND 180),
    created_by BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    processed_by BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    created_brand_id BIGINT REFERENCES brand(brand_id) ON DELETE SET NULL,
    created_branch_id BIGINT REFERENCES branch(branch_id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_submission_status_created ON submission(status, created_at);

CREATE TABLE IF NOT EXISTS brand_translation (
    brand_id BIGINT NOT NULL REFERENCES brand(brand_id) ON DELETE CASCADE,
    language_code VARCHAR(10) NOT NULL REFERENCES language(language_code) ON DELETE RESTRICT,
    translated_name VARCHAR(160),
    translated_description TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (brand_id, language_code)
);

CREATE TABLE IF NOT EXISTS branch_translation (
    branch_id BIGINT NOT NULL REFERENCES branch(branch_id) ON DELETE CASCADE,
    language_code VARCHAR(10) NOT NULL REFERENCES language(language_code) ON DELETE RESTRICT,
    translated_name VARCHAR(180),
    translated_description TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (branch_id, language_code)
);

CREATE TABLE IF NOT EXISTS menu_item_translation (
    menu_item_id BIGINT NOT NULL REFERENCES menu_item(menu_item_id) ON DELETE CASCADE,
    language_code VARCHAR(10) NOT NULL REFERENCES language(language_code) ON DELETE RESTRICT,
    translated_name VARCHAR(180),
    translated_description TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (menu_item_id, language_code)
);

CREATE TABLE IF NOT EXISTS visit_session (
    session_id UUID PRIMARY KEY,
    user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activity_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    device_type VARCHAR(30),
    referrer TEXT,
    is_admin_session BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_visit_session_started_at ON visit_session(started_at);

CREATE TABLE IF NOT EXISTS page_view (
    page_view_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID REFERENCES visit_session(session_id) ON DELETE SET NULL,
    page_path TEXT NOT NULL,
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    brand_id BIGINT REFERENCES brand(brand_id) ON DELETE SET NULL,
    branch_id BIGINT REFERENCES branch(branch_id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_page_view_viewed_at ON page_view(viewed_at);
CREATE INDEX IF NOT EXISTS ix_page_view_brand ON page_view(brand_id, viewed_at);
CREATE INDEX IF NOT EXISTS ix_page_view_branch ON page_view(branch_id, viewed_at);

-- Only persist geolocation if the visitor explicitly consents. It is not needed merely to render the map.
CREATE TABLE IF NOT EXISTS visitor_location (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID REFERENCES visit_session(session_id) ON DELETE CASCADE,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    consent_status VARCHAR(20) NOT NULL CHECK (consent_status IN ('GRANTED','REVOKED'))
);

CREATE TABLE IF NOT EXISTS audio_play (
    audio_play_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT REFERENCES brand(brand_id) ON DELETE SET NULL,
    branch_id BIGINT REFERENCES branch(branch_id) ON DELETE SET NULL,
    session_id UUID REFERENCES visit_session(session_id) ON DELETE SET NULL,
    language_code VARCHAR(10) NOT NULL REFERENCES language(language_code) ON DELETE RESTRICT,
    played_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_audio_play_played_at ON audio_play(played_at);

CREATE TABLE IF NOT EXISTS admin_audit_log (
    audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES user_account(user_id) ON DELETE RESTRICT,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id VARCHAR(100) NOT NULL,
    language_code VARCHAR(10) REFERENCES language(language_code) ON DELETE SET NULL,
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_admin_audit_created_at ON admin_audit_log(created_at);
CREATE INDEX IF NOT EXISTS ix_admin_audit_entity ON admin_audit_log(entity_type, entity_id);

-- Seed only reference data and the ten requested brands. Operational tables remain empty until users/admins perform actions.
